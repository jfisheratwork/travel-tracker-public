/**
 * Unified static places catalog combining curated National Parks,
 * Crown Jewels State/Provincial Parks, and Key Cities.
 */
export const STATIC_PLACES_CATALOG: Place[] = [
  ...CURATED_NATIONAL_PARKS,
  ...CROWN_JEWELS_STATE_PARKS,
  ...CURATED_CITIES,
];

/**
 * Fast O(1) in-memory lookup map for all static places.
 * Indexed by primary Place ID (e.g., 'np-yosemite', 'city-chicago') as well as
 * legacy / canonical names for seamless lookup.
 */
export const STATIC_PLACES_MAP = new Map<string, Place>();

// Populate primary and alias keys
for (const place of STATIC_PLACES_CATALOG) {
  STATIC_PLACES_MAP.set(place.id, place);
  // Also register normalized name as an alias if not colliding
  const nameKey = place.name.toLowerCase().trim();
  if (!STATIC_PLACES_MAP.has(nameKey)) {
    STATIC_PLACES_MAP.set(nameKey, place);
  }
}

/**
 * Look up a static place by id or name in O(1) time.
 */
export function getStaticPlace(idOrName: string): Place | undefined {
  if (!idOrName) return undefined;
  return STATIC_PLACES_MAP.get(idOrName) || STATIC_PLACES_MAP.get(idOrName.toLowerCase().trim());
}

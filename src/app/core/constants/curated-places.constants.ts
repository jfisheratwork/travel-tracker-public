/**
 * Curated US and Canadian National Parks mapped as Place entities.
 */
export const CURATED_NATIONAL_PARKS: Place[] = NATIONAL_PARKS.map((p) => {
  const isCanada = p.country === 'Canada';
  const countryId = isCanada ? 'CA' : 'US';
  const primarySub = p.sub ? p.sub.split('/')[0] : '';
  const regionId = primarySub ? `${countryId}-${primarySub}` : undefined;
  const slug = 'np-' + p.id.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return {
    id: slug,
    name:
      p.name.includes('Park') || p.name.includes('Preserve') ? p.name : `${p.name} National Park`,
    category: 'national_park',
    countryId,
    regionId,
    lat: p.lat,
    lng: p.lng,
    source: 'static',
    isCurated: true,
    tags: ['national_park', 'nature', 'scenic'],
  };
});

